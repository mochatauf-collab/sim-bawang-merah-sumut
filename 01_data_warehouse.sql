-- Jalankan HANYA pada database db_pusat_sumut di Neon.
-- Asumsi tabel sumber produksi_bawang_merah_pusat sudah ada.
CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_kabupaten (
  kabupaten_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kabupaten VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_kecamatan (
  kecamatan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kabupaten_id INTEGER NOT NULL REFERENCES dw.dim_kabupaten(kabupaten_id),
  nama_kecamatan VARCHAR(100) NOT NULL,
  UNIQUE (kabupaten_id, nama_kecamatan)
);

CREATE TABLE IF NOT EXISTS dw.dim_waktu (
  tahun INTEGER PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS dw.fact_produksi (
  kode_data VARCHAR(20) PRIMARY KEY,
  kecamatan_id INTEGER NOT NULL REFERENCES dw.dim_kecamatan(kecamatan_id),
  tahun INTEGER NOT NULL REFERENCES dw.dim_waktu(tahun),
  komoditas VARCHAR(50) NOT NULL,
  produksi_ton NUMERIC(14,2) NOT NULL,
  wilayah_sumber VARCHAR(100),
  updated_at TIMESTAMPTZ
);

-- Dimensi dan fakta dapat dimuat ulang setelah sinkronisasi Colab.
INSERT INTO dw.dim_kabupaten (nama_kabupaten)
SELECT DISTINCT kabupaten
FROM public.produksi_bawang_merah_pusat
WHERE kabupaten IS NOT NULL
ON CONFLICT (nama_kabupaten) DO NOTHING;

INSERT INTO dw.dim_kecamatan (kabupaten_id, nama_kecamatan)
SELECT DISTINCT k.kabupaten_id, p.kecamatan
FROM public.produksi_bawang_merah_pusat p
JOIN dw.dim_kabupaten k ON k.nama_kabupaten = p.kabupaten
WHERE p.kecamatan IS NOT NULL
ON CONFLICT (kabupaten_id, nama_kecamatan) DO NOTHING;

INSERT INTO dw.dim_waktu (tahun)
SELECT DISTINCT tahun
FROM public.produksi_bawang_merah_pusat
WHERE tahun IS NOT NULL
ON CONFLICT (tahun) DO NOTHING;

INSERT INTO dw.fact_produksi
(kode_data, kecamatan_id, tahun, komoditas, produksi_ton, wilayah_sumber, updated_at)
SELECT p.kode_data, c.kecamatan_id, p.tahun, p.komoditas,
       p.produksi_ton, p.wilayah_sumber, p.updated_at
FROM public.produksi_bawang_merah_pusat p
JOIN dw.dim_kabupaten k ON k.nama_kabupaten = p.kabupaten
JOIN dw.dim_kecamatan c ON c.kabupaten_id = k.kabupaten_id
                      AND c.nama_kecamatan = p.kecamatan
JOIN dw.dim_waktu w ON w.tahun = p.tahun
ON CONFLICT (kode_data) DO UPDATE SET
    kecamatan_id = EXCLUDED.kecamatan_id,
    tahun = EXCLUDED.tahun,
    komoditas = EXCLUDED.komoditas,
    produksi_ton = EXCLUDED.produksi_ton,
    wilayah_sumber = EXCLUDED.wilayah_sumber,
    updated_at = EXCLUDED.updated_at;

CREATE OR REPLACE VIEW dw.v_analisis_produksi AS
SELECT f.kode_data, k.nama_kabupaten AS kabupaten,
       c.nama_kecamatan AS kecamatan, f.tahun, f.komoditas,
       f.produksi_ton, f.wilayah_sumber, f.updated_at
FROM dw.fact_produksi f
JOIN dw.dim_kecamatan c ON f.kecamatan_id = c.kecamatan_id
JOIN dw.dim_kabupaten k ON c.kabupaten_id = k.kabupaten_id;

SELECT COUNT(*) AS jumlah_baris,
       COUNT(DISTINCT kabupaten) AS kabupaten,
       SUM(produksi_ton) AS total_ton
FROM dw.v_analisis_produksi;
